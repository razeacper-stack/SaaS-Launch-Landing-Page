/**
 * Retrieve translation for a specific language and key, resolving aliases gracefully.
 */
export function getTranslation(lang, key) {
  const dict = translations[lang] || translations.en;
  if (dict[key] !== undefined) {
    return dict[key];
  }
  const alias = keyAliases[key];
  if (alias && dict[alias] !== undefined) {
    return dict[alias];
  }
  // Fallback to English if missing in target lang
  if (lang !== "en") {
    const enDict = translations.en;
    if (enDict[key] !== undefined) return enDict[key];
    if (alias && enDict[alias] !== undefined) return enDict[alias];
  }
  return null;
}
